class DashboardStore {
  constructor() {
    this.data = this.load();
  }

  load() {
    try {
      let stored = localStorage.getItem(STORAGE_KEY);
      if (!stored) {
        stored = localStorage.getItem('BONORNG_NGS_DASHBOARD_DATA_V1');
      }
      if (stored) {
        const parsed = JSON.parse(stored);
        if (parsed && parsed.profile) {
          parsed.profile.schoolName = 'វិទ្យាល័យព្រះយុគន្ធរ សាលារៀនជំនាន់ថ្មី';
          if (!parsed.profile.role || parsed.profile.role === 'គ្រូបង្រៀន') {
            parsed.profile.role = 'គ្រូបង្រៀនគណិតវិទ្យា NGS';
          }
          if (!parsed.profile.avatar || parsed.profile.avatar.includes('dicebear')) {
            parsed.profile.avatar = 'teacher-profile.jpg';
          }
          this.save(parsed);
          return parsed;
        }
      }
    } catch (e) {
      console.error('Error reading localStorage', e);
    }
    this.save(defaultData);
    return defaultData;
  }

  save(dataToSave = null) {
    if (dataToSave) this.data = dataToSave;
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(this.data));
    } catch (e) {
      console.error('Error saving to localStorage', e);
    }
  }

  reset() {
    this.data = JSON.parse(JSON.stringify(defaultData));
    this.save();
    return this.data;
  }

  exportJSON() {
    const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(this.data, null, 2));
    const dlAnchorElem = document.createElement('a');
    dlAnchorElem.setAttribute('href', dataStr);
    dlAnchorElem.setAttribute('download', `NGS_Teacher_Bonorng_Backup_${new Date().toISOString().slice(0, 10)}.json`);
    dlAnchorElem.click();
  }

  importJSON(jsonString) {
    try {
      const parsed = JSON.parse(jsonString);
      if (parsed && parsed.profile) {
        this.data = parsed;
        this.save();
        return true;
      }
    } catch (e) {
      console.error('Invalid JSON', e);
    }
    return false;
  }
}

window.appStore = new DashboardStore();

